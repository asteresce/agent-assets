//! Compile the shipped registry into the binary.
//!
//! `assets/` is walked at build time and emitted as a static table of
//! `include_bytes!`, so a built `agent-assets` carries its own registry and
//! runs with nothing beside it. `--assets` stays the way for a consumer to
//! substitute another registry.
//!
//! What the walk embeds is what `assets/spec.json` declares: the shape each
//! category has, and the extension its file assets carry. Undeclared
//! categories and the wrong shape are not embedded — `tests/registry.rs`
//! reports them against the same declaration.
//!
//! The walk mirrors `registry::walk_files`: symlinks are skipped rather than
//! followed, and entries are sorted so the generated file is byte-stable.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

/// What `assets/spec.json` declares about one category — only the shape
/// build.rs embeds by. The section schema and the entry file are the
/// runtime's business and are read there.
#[derive(Deserialize)]
struct CategoryDecl {
    kind: Kind,
    #[serde(default)]
    extension: Option<String>,
}

fn main() {
    println!("cargo:rerun-if-changed=assets");

    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let assets = manifest_dir.join("assets");
    let specs = load_specs(&assets);

    let mut table = String::from("// @generated by build.rs from assets/. Do not edit.\n");
    table.push_str("pub static EMBEDDED: &[EmbeddedAsset] = &[\n");

    for category in sorted_children(&assets) {
        let category_dir = assets.join(&category);
        if kind_of(&category_dir) != Some(Kind::Dir) {
            continue;
        }
        // Undeclared categories hold no assets the engine may load.
        let Some(decl) = specs.get(&category) else {
            continue;
        };
        match decl.kind {
            Kind::Dir => {
                for child in sorted_children(&category_dir) {
                    let path = category_dir.join(&child);
                    if kind_of(&path) != Some(Kind::Dir) || is_catalog_index(&child) {
                        continue;
                    }
                    let mut files = Vec::new();
                    walk(&path, Path::new(""), &mut files);
                    files.sort();
                    push_asset(
                        &mut table,
                        &category,
                        &child,
                        "AssetKind::Dir",
                        &format!("assets/{category}/{child}"),
                        &files,
                    );
                }
            }
            Kind::File => {
                let extension = decl
                    .extension
                    .as_deref()
                    .filter(|extension| !extension.is_empty())
                    .unwrap_or_else(|| {
                        panic!(
                            "assets/spec.json: {category} is a file category without `extension`"
                        )
                    });
                let suffix = format!(".{extension}");
                for child in sorted_children(&category_dir) {
                    let path = category_dir.join(&child);
                    if kind_of(&path) != Some(Kind::File) {
                        continue;
                    }
                    let Some(name) = child.strip_suffix(&suffix) else {
                        continue;
                    };
                    if is_catalog_index(name) {
                        continue;
                    }
                    push_asset(
                        &mut table,
                        &category,
                        name,
                        "AssetKind::File",
                        &format!("assets/{category}"),
                        &[PathBuf::from(&child)],
                    );
                }
            }
        }
    }

    table.push_str("];\n");

    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("embedded_registry.rs");
    fs::write(&out, table).expect("cannot write embedded_registry.rs");
}

/// The shape declarations from `assets/spec.json`. Lenient about the keys
/// build.rs does not need — the runtime parses the same file strictly, and
/// `tests/registry.rs` conforms it — but not about a missing or malformed
/// file: the table would have nothing to be built from.
fn load_specs(assets: &Path) -> BTreeMap<String, CategoryDecl> {
    let path = assets.join("spec.json");
    let text =
        fs::read_to_string(&path).unwrap_or_else(|e| panic!("cannot read {}: {e}", path.display()));
    serde_json::from_str(&text)
        .unwrap_or_else(|e| panic!("assets/spec.json is not valid JSON: {e}"))
}

/// The name a category reserves for its catalog index: documentation about
/// the category, not an asset. Same call as `registry.rs`.
fn is_catalog_index(name: &str) -> bool {
    name == "README"
}

/// One `EmbeddedAsset { … }` entry, with `include_bytes!` for every file.
fn push_asset(
    table: &mut String,
    category: &str,
    name: &str,
    kind: &str,
    prefix: &str,
    files: &[PathBuf],
) {
    table.push_str("    EmbeddedAsset {\n");
    table.push_str(&format!("        category: {},\n", quote(category)));
    table.push_str(&format!("        name: {},\n", quote(name)));
    table.push_str(&format!("        kind: {kind},\n"));
    table.push_str("        files: &[\n");
    for relative in files {
        let manifest_relative = format!("{prefix}/{}", relative.display());
        table.push_str("            EmbeddedFile {\n");
        table.push_str(&format!(
            "                rel: {},\n",
            quote(&relative.to_string_lossy())
        ));
        table.push_str(&format!(
            "                bytes: include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), {})),\n",
            quote(&format!("/{manifest_relative}"))
        ));
        table.push_str("            },\n");
    }
    table.push_str("        ],\n");
    table.push_str("    },\n");
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "snake_case")]
enum Kind {
    File,
    Dir,
}

/// `None` for a symlink or anything that is neither a file nor a directory.
fn kind_of(path: &Path) -> Option<Kind> {
    let metadata = fs::symlink_metadata(path).ok()?;
    let file_type = metadata.file_type();
    if file_type.is_symlink() {
        return None;
    }
    if file_type.is_file() {
        return Some(Kind::File);
    }
    if file_type.is_dir() {
        return Some(Kind::Dir);
    }
    None
}

fn sorted_children(dir: &Path) -> Vec<String> {
    let mut out: Vec<String> = match fs::read_dir(dir) {
        Ok(entries) => entries
            .flatten()
            .map(|entry| entry.file_name().to_string_lossy().into_owned())
            .collect(),
        Err(_) => Vec::new(),
    };
    out.sort();
    out
}

/// Every regular file under `root`, as paths relative to `root`. Symlinks are
/// skipped: a link inside the registry is not content the engine should copy.
fn walk(root: &Path, rel: &Path, out: &mut Vec<PathBuf>) {
    let dir = if rel.as_os_str().is_empty() {
        root.to_path_buf()
    } else {
        root.join(rel)
    };
    let Ok(entries) = fs::read_dir(&dir) else {
        return;
    };
    for entry in entries.flatten() {
        let child_rel = rel.join(entry.file_name());
        match kind_of(&entry.path()) {
            Some(Kind::File) => out.push(child_rel),
            Some(Kind::Dir) => walk(root, &child_rel, out),
            None => {}
        }
    }
}

fn quote(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for character in text.chars() {
        match character {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}
